import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/obsigama/index.ts"],
  bundle: true,
  write: false,
  platform: "node",
  target: "es2020",
  format: "iife",
  globalName: "HELLVAULT_OBSIGAMA",
  external: ["obsidian"],
  legalComments: "none",
});
const originalGame = await readFile(new URL("../src/hellvault.js", import.meta.url), "utf8");
const music = await readFile(new URL("../src/music.js", import.meta.url), "utf8");
const header = "// Generated by npm run build; edit src/hellvault.js, src/music.js or src/obsigama/ instead.\n";
await writeFile(new URL("../main.js", import.meta.url), header + result.outputFiles[0].text + "\n" + music + "\n" + originalGame);
